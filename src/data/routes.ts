export function getIndexedRoutes(): Route[] {
  return routes.filter((r) => r.index);
}

export function getRoutesByOrigin(originId: string): Route[] {
  return routes.filter((r) => r.origin === originId && r.index);
}

export function getRoutesByDestination(destinationId: string): Route[] {
  return routes.filter((r) => r.destination === destinationId && r.index);
}

export function getRoutesForCity(cityId: string): Route[] {
  return routes.filter(
    (r) => (r.origin === cityId || r.destination === cityId) && r.index
  );
}
